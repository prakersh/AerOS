class TestExtractionMimeRouting:
    """Verify that the upload endpoint passes the correct MIME type to
    the extraction pipeline for each file format."""

    @pytest.mark.parametrize(
        "fixture_file,mime_type",
        [
            ("quote_freshfarm.csv", "text/csv"),
            (
                "quote_metro.xlsx",
                "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            ),
            ("quote_bakery.pdf", "application/pdf"),
            (
                "quote_kirana.docx",
                "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
            ),
            ("quote_greenvalley.png", "image/png"),
            ("quote_daily.txt", "text/plain"),
            ("quote_annapurna.html", "text/html"),
        ],
        ids=["csv", "xlsx", "pdf", "docx", "png", "txt", "html"],
    )
    def test_mime_type_passed_to_extraction(
        self,
        vendor_auth_client,
        dispatched_rfx,
        session,
        fixture_file: str,
        mime_type: str,
    ) -> None:
        """The attachment stored in the DB should have the correct MIME type."""
        filepath = FIXTURES_DIR / fixture_file
        assert filepath.exists(), f"Fixture missing: {filepath}"

        mock_provider = AsyncMock()
        mock_provider.chat.return_value = _mock_chat_response(_extraction_json())

        mock_vision = AsyncMock()
        from aeros.ai.base import VisionResponse

        mock_vision.vision.return_value = VisionResponse(
            content="Extracted text from image"
        )

        with (
            open(filepath, "rb") as f,
            patch("aeros.ai.factory.get_chat_provider", return_value=mock_provider),
            patch("aeros.ai.factory.get_vision_provider", return_value=mock_vision),
        ):
            resp = vendor_auth_client.post(
                f"/api/vendor/rfx/{dispatched_rfx.id}/upload",
                files={"file": (fixture_file, f, mime_type)},
            )

        assert resp.status_code == 200
        data = resp.json()

        # Verify the Attachment record has the correct MIME type
        from sqlmodel import select

        att = session.exec(
            select(Attachment).where(Attachment.id == data["attachment_id"])
        ).first()
        assert att is not None
        assert att.mime_type == mime_type


class TestOfferCreation:
    """Verify that a successful extraction creates an Offer for each format."""

    @pytest.mark.parametrize(
        "fixture_file,mime_type",
        [
            ("quote_freshfarm.csv", "text/csv"),
            (
                "quote_metro.xlsx",
                "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            ),
            ("quote_bakery.pdf", "application/pdf"),
            (
                "quote_kirana.docx",
                "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
            ),
            ("quote_greenvalley.png", "image/png"),
            ("quote_daily.txt", "text/plain"),
            ("quote_annapurna.html", "text/html"),
        ],
        ids=["csv", "xlsx", "pdf", "docx", "png", "txt", "html"],
    )
    def test_offer_created_after_upload(
        self,
        vendor_auth_client,
        dispatched_rfx,
        vendor_record,
        session,
        fixture_file: str,
        mime_type: str,
    ) -> None:
        """Upload + extraction should produce an Offer linked to the RFx."""
        _, vendor = vendor_record
        filepath = FIXTURES_DIR / fixture_file
        assert filepath.exists(), f"Fixture missing: {filepath}"

        mock_provider = AsyncMock()
        mock_provider.chat.return_value = _mock_chat_response(_extraction_json())

        mock_vision = AsyncMock()
        from aeros.ai.base import VisionResponse

        mock_vision.vision.return_value = VisionResponse(
            content="Extracted text from image"
        )

        with (
            open(filepath, "rb") as f,
            patch("aeros.ai.factory.get_chat_provider", return_value=mock_provider),
            patch("aeros.ai.factory.get_vision_provider", return_value=mock_vision),
        ):
            resp = vendor_auth_client.post(
                f"/api/vendor/rfx/{dispatched_rfx.id}/upload",
                files={"file": (fixture_file, f, mime_type)},
            )

        assert resp.status_code == 200

        # Check that an Offer was created
        from sqlmodel import select

        offer = session.exec(
            select(Offer).where(
                Offer.rfx_id == dispatched_rfx.id,
                Offer.vendor_id == vendor.id,
            )
        ).first()
        assert offer is not None, f"No Offer created for {fixture_file}"
        assert offer.total_quote == 46100.0
        assert offer.currency == "INR"
        assert offer.payment_terms == "NET15"

        # Verify vendor lane status updated to QUOTED
        rv = session.exec(
            select(RFxVendor).where(
                RFxVendor.rfx_id == dispatched_rfx.id,
                RFxVendor.vendor_id == vendor.id,
            )
        ).first()
        assert rv is not None
        assert rv.status == RFxVendorStatus.QUOTED
