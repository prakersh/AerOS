def _extraction_json(
    sku_name: str = "Full Cream Milk",
    qty: float = 200,
    unit: str = "ltr",
    unit_price: float = 56.0,
    total: float = 11200.0,
    total_quote: float = 46100.0,
) -> str:
    """Return realistic extraction JSON for mocked LLM responses."""
    return json.dumps({
        "line_items": [
            {
                "sku_name": sku_name,
                "qty": qty,
                "unit": unit,
                "unit_price": unit_price,
                "total": total,
                "confidence_per_field": {"unit_price": 0.95, "qty": 0.98},
            },
        ],
        "total_quote": total_quote,
        "currency": "INR",
        "payment_terms": "NET15",
        "delivery_terms": "doorstep",
        "lead_time_hours": 24,
        "confidence_overall": 0.92,
    })


